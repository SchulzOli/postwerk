// Writes src/print-fonts.ts: the typefaces print PDFs embed (latin subset, WOFF),
// inlined so rendering needs no font files at runtime (web, worker and tests alike).
// Run after updating the @fontsource packages: npm run fonts --workspace=@maas/core
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const fonts = {
  sans: { regular: '@fontsource/source-sans-3/files/source-sans-3-latin-400-normal.woff', bold: '@fontsource/source-sans-3/files/source-sans-3-latin-700-normal.woff' },
  serif: { regular: '@fontsource/source-serif-4/files/source-serif-4-latin-400-normal.woff', bold: '@fontsource/source-serif-4/files/source-serif-4-latin-700-normal.woff' },
};
const version = (name) => JSON.parse(readFileSync(require.resolve(`${name}/package.json`), 'utf8')).version;

let out = `// Generated by scripts/print-fonts.mjs, do not edit.
// Source Sans 3 ${version('@fontsource/source-sans-3')} and Source Serif 4 ${version('@fontsource/source-serif-4')} (latin subset, WOFF),
// © Adobe, licensed under the SIL Open Font License 1.1 (https://openfontlicense.org).

/** Base64 WOFF font files, by brand typeface and weight. */
export const PRINT_FONTS = {\n`;
for (const [family, weights] of Object.entries(fonts)) {
  out += `  ${family}: {\n`;
  for (const [weight, file] of Object.entries(weights)) out += `    ${weight}: '${readFileSync(require.resolve(file)).toString('base64')}',\n`;
  out += '  },\n';
}
out += '} as const;\n';
writeFileSync(new URL('../src/print-fonts.ts', import.meta.url), out);
console.log('wrote src/print-fonts.ts');
