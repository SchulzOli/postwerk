/** "1 d 2 h 30 min" / "1 T 2 Std. 30 Min.": a delay of 60 minutes or more. */
export function formatMinutes(minutes: number, t: (typeof canvasMessages)['en']): string {
  if (minutes < 60) return t.duration.minutes(minutes);
  const days = Math.floor(minutes / 1440);
  const hours = Math.floor((minutes % 1440) / 60);
  const rest = minutes % 60;
  return [days && t.duration.days(days), hours && t.duration.hours(hours), rest && t.duration.minutes(rest)].filter(Boolean).join(' ');
}
